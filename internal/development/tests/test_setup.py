    assert path.read_bytes() == b"[]\n"
    assert Path(backup).read_bytes() == b"{}\n"
    Path(backup).unlink()
    if sys.platform == "win32":
        assert waited >= 0.3, "it waited for the file to be closed, rather than failing"


