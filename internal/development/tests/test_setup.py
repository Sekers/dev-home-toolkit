def test_a_read_only_settings_file_is_never_planned_or_written(box: Sandbox) -> None:
    path = box.root / "plans" / "read-only.json"
    path.parent.mkdir(exist_ok=True)
    path.write_bytes(b"{}\n")
    path.chmod(stat.S_IREAD)
    try:
        plan = shared_module(box, "claude_settings").plan(path, ENTRIES)
        with pytest.raises(PermissionError):
            shared_module(box, "settings_files").write_settings_file(
                path, "[]\n", bom=False, backup=True
            )
        left = sorted(entry.name for entry in path.parent.glob("read-only.json*"))
    finally:
        path.chmod(stat.S_IREAD | stat.S_IWRITE)
    assert plan.reason == "it is read-only", plan.reason
    assert path.read_bytes() == b"{}\n"
    assert left == ["read-only.json"], "no backup and no new file left beside it"


def test_a_settings_file_held_open_for_a_moment_is_still_replaced(box: Sandbox) -> None:
    # Windows refuses to replace a file another program has open, as antivirus may for a moment.
    path = box.root / "plans" / "held.json"
    path.parent.mkdir(exist_ok=True)
    path.write_bytes(b"{}\n")
    held = path.open("rb")
    timer = threading.Timer(0.3, held.close)
    started = time.monotonic()
    timer.start()
    try:
        backup = shared_module(box, "settings_files").write_settings_file(
            path, "[]\n", bom=False, backup=True
        )
    finally:
        timer.cancel()
        held.close()
    waited = time.monotonic() - started
    assert path.read_bytes() == b"[]\n"
    assert Path(backup).read_bytes() == b"{}\n"
    Path(backup).unlink()
    if sys.platform == "win32":
        assert waited >= 0.3, "it waited for the file to be closed, rather than failing"


