def test_the_requirements_checker_applies_each_types_rule(box: Sandbox) -> None:
    requirements = shared_module(box, "requirements")
    settings = shared_module(box, "settings")
    needs, unmet = requirements.Requirement, requirements.Unmet
    pc = requirements.ThisPC("windows", (3, 13, 2), frozenset({"gh"}))

    def check(*requires: object, agents: tuple[str, ...] = ("claude-code",)) -> list[object]:
        return list(requirements.unmet(requires, pc, agents))

    met = [
        needs("os", ("macos", "windows")),
        needs("agent", ("claude-code", "codex")),
        needs("program", ("gh",)),
        needs("python", version=(3, 13)),
        needs("python", version=(3, 13, 2)),
    ]
    assert check(*met) == [] and check(*met, agents=("codex",)) == []
    assert check(needs("os", ("macos", "linux"))) == [
        unmet("works only on macOS or Linux", keeps_off=True, can_act=False, per_folder=False)
    ]
    # An agent is checked for each skills folder, against every agent setup sets up that reads it.
    assert check(needs("agent", ("claude-code",)), agents=("codex",)) == [
        unmet("works only in Claude Code", keeps_off=True, can_act=True, per_folder=True)
    ]
    assert check(needs("agent", ("codex",)), agents=("codex", "claude-code")) == [
        unmet("works only in Codex", keeps_off=True, can_act=True, per_folder=True)
    ]
    # A program or a Python version only warns.
    jira = needs("program", ("jira",), "filing Jira issues")
    assert check(jira, needs("program", ("glab",)), needs("python", version=(3, 13, 3))) == [
        unmet(
            "jira isn't on the PATH, and the skill uses it for filing Jira issues",
            keeps_off=False,
            can_act=True,
            per_folder=False,
        ),
        unmet("glab isn't on the PATH", keeps_off=False, can_act=True, per_folder=False),
        unmet(
            "the skill needs Python 3.13.3 or later, and this PC's is 3.13.2",
            keeps_off=False,
            can_act=True,
            per_folder=False,
        ),
    ]
    # Anything under supportedOn that can't be used keeps the skill off, a type it doesn't know
    # included, and is never warned about.
    mistake = "has a mistake in its dev-home-skill.json"
    for broken in (needs("os", mistake=True), needs("", mistake=True)):
        assert check(broken) == [unmet(mistake, keeps_off=True, can_act=True, per_folder=False)]
    broken_ones = [needs("os", mistake=True), needs("", mistake=True)]
    assert requirements.warned_about([*met, *broken_ones]) == tuple(met[2:])
    names = requirements.either(["windows", "macos", "linux"], requirements.OPERATING_SYSTEMS)
    assert names == "Windows, macOS, or Linux"
    # Every tool setup sets up has a name a requirement can give it.
    assert set(requirements.AGENTS.values()) == {tool.name for tool in settings.TOOLS}


